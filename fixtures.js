const pg = require('pg');

// If you want to run it form host machine
//require('dotenv').config();

let client = new pg.Client({
    user: 'postgres',
    host: 'db',
    database: 'notes',
    port: 5431,
    password: 'myscretpassword',
});
client.connect().then((r) => console.log('Client connected successfully'));


const CREATE_TABLE = `
    DROP TABLE if exists secure_notes;
    DROP TABLE if exists users;
    CREATE TABLE users (
       id int generated by default as identity,
       username varchar(150) NOT NULL,
       email varchar(200) NOT NULL UNIQUE,
       pwhash varchar(72) NOT NULL,
       primary key (id)
    );
    CREATE TABLE secure_notes (
       id int generated by default as identity,
       label varchar(150),
       description text,
       created_at timestamp,
       updated_at timestamp,
       owner int,
       fnames varchar(300),
       primary key (id),
       foreign key (owner) references users(id)
    );
`;

const CLEANUP = `
    DROP TABLE if exists secure_notes;
    DROP TABLE if exists users;
`;


async function buildTables() {
    try {
        const promises = [CREATE_TABLE].map((query) => {
            console.log('Executing query...', query);
            return client.query(query)
        });
        await Promise.all(promises);
    } catch (e) {
        console.error(e);
    }
}

async function cleanUp() {
    try {
        await client.query(CLEANUP);
        console.log('Cleaned up tables successfully');
    } catch (e) {
        console.log(e);
    }
}

buildTables().then(() => {
    process.exit(0);
}, (err) => {
    console.log(err);
    cleanUp();
});

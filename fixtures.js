const pg = require('pg');
const bcrypt = require('bcryptjs');


let client = new pg.Client({
    user: 'madhu',
    password: 'password',
    database: 'notes',
    host: '127.0.0.1',
    post: 5432
});
client.connect().then((r) => console.log('Client connected successfully'));

let users = [{ username: 'madhu', email: 'test@gmail.com', password: 'password'}];

const SALT_ROUNDS = 2;

const notes = [
    {
        label: 'A note',
        description: 'I will be okay',
        created_at: new Date().toISOString(),
        owner: 1
    },
    {
        label: 'A note 2',
        description: 'I will be okay',
        created_at: new Date().toISOString(),
        owner: 1
    }
]

const CREATE_TABLE = `
    DROP TABLE if exists secure_notes;
    DROP TABLE if exists users;
    CREATE TABLE users (
       id int generated by default as identity,
       username varchar(150) NOT NULL,
       email varchar(200) NOT NULL UNIQUE,
       pwhash varchar(72) NOT NULL,
       primary key (id)
    );
    CREATE TABLE secure_notes (
       id int generated by default as identity,
       label varchar(150),
       description text,
       created_at timestamp,
       owner int,
       primary key (id),
       foreign key (owner) references users(id)
    );
`;


async function prepareUsers(users){
    const ans = [];
    for (let user of users) {
        const pwhash = await bcrypt.hash(user.password, SALT_ROUNDS);
        ans.push({...user, pwhash});
    }
    return ans;
};

const createInsert = (table, columns, tuples) => {
    // tuples is a list of lists
    const parens = tuples.map((tup) => {
        const mid = columns.map((col) => `'${tup[col]}'`).join(',')
        return '(' + mid + ')';
    });
    return `INSERT INTO ${table} (${columns.join(',')}) values ${parens.join(',')};`;
}
const CLEANUP = `
    DROP TABLE if exists secure_notes;
    DROP TABLE if exists users;
`;


async function buildTables() {
    try {
        users = await prepareUsers(users);

        const INSERT_TABLES_USERS = createInsert('users', ['username', 'email', 'pwhash'], users);
        const INSERT_TABLES_NOTES = createInsert('secure_notes', ['label', 'description', 'created_at', 'owner'], notes);

        console.log(users);
        const promises = [CREATE_TABLE, INSERT_TABLES_USERS, INSERT_TABLES_NOTES].map((query) => {
            console.log('Executing query...', query);
            return client.query(query)
        });
        const results = await Promise.all(promises);
        console.log(`Created tables and data successfully - ${JSON.stringify(results)}`);
    } catch (e) {
        console.error(e);
    }
}

async function cleanUp() {
    try {
        await client.query(CLEANUP);
        console.log('Cleaned up tables successfully');
    } catch (e) {
        console.log(e);
    }
}

buildTables().then(() => {
    process.exit(0);
}, (err) => {
    cleanUp();
});
